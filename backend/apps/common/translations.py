def translate(value):
    if get_language() != "kk":
        return value
    if isinstance(value, dict):
        return {key: translate(item) for key, item in value.items()}
    if isinstance(value, list):
        return [translate(item) for item in value]
    return KAZAKH.get(str(value), value)
